import React from 'react'
import ReactDOM from 'react-dom/client'
import { registerSW } from 'virtual:pwa-register'
import App from './App'
import './index.css'

// autoUpdate: silently activates a new service worker version as soon as
// it's installed, so returning customers always get the latest app shell
// without a manual "refresh to update" prompt.
registerSW({ immediate: true })

ReactDOM.createRoot(document.getElementById('root')).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>
)
